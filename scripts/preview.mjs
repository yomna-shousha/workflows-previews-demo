#!/usr/bin/env node
// Gives each Worker Preview its own Workflow, until Cloudflare provisions one automatically.
//
//   node scripts/preview.mjs deploy  --name pr-12   deploy the Preview and its Workflow
//   node scripts/preview.mjs delete  --name pr-12   delete both
//   node scripts/preview.mjs config  --name pr-12   only write the generated configs
//
// A Preview cannot own a Workflow today: a Workflow binding in `previews` points at an
// existing Workflow, which runs its own Worker's code and bindings. So for each Preview this
// script deploys a companion Worker from the same branch, `<worker>-<preview>`, that owns:
//
//   - one Workflow per top-level `workflows` entry, renamed `<workflow>-<preview>`
//   - the Durable Object classes, in a namespace of its own
//
// The Preview is then bound to the companion's Workflows and Durable Objects (`script_name`),
// so the Preview's fetch handler and the Workflow both read and write the same per-Preview
// state, running the branch's code. Production is never touched.

import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync, appendFileSync } from "node:fs";
import { parse, printParseErrorCode } from "jsonc-parser";

const CONFIG = "wrangler.jsonc";
const PREVIEW_CONFIG = "wrangler.ci-preview.jsonc";
const COMPANION_CONFIG = "wrangler.ci-workflows.jsonc";
const MAX_NAME = 63;

// Top-level keys the companion must not inherit: it is only reached through bindings, and
// must never take over production triggers.
const COMPANION_DROP = [
  "previews", "routes", "route", "triggers", "queues", "tail_consumers",
  "streaming_tail_consumers", "assets", "site", "env",
];

function parseArgs(argv) {
  const [command, ...rest] = argv;
  if (!["deploy", "delete", "config"].includes(command)) {
    throw new Error("Usage: preview.mjs <deploy|delete|config> [--name <preview>]");
  }
  const i = rest.indexOf("--name");
  const name = (i >= 0 ? rest[i + 1] : process.env.PREVIEW_NAME) ?? gitBranch();
  return { command, previewName: slugify(name) };
}

function gitBranch() {
  return spawnSync("git", ["rev-parse", "--abbrev-ref", "HEAD"], { encoding: "utf8" }).stdout.trim();
}

function slugify(value) {
  const slug = String(value).toLowerCase().replace(/[^a-z0-9-]+/g, "-").replace(/^-+|-+$/g, "");
  if (!slug) throw new Error("Preview name is empty; pass --name or set PREVIEW_NAME");
  return slug;
}

function readConfig() {
  const errors = [];
  const config = parse(readFileSync(CONFIG, "utf8"), errors, { allowTrailingComma: true });
  if (errors.length) {
    throw new Error(`${CONFIG}: ${errors.map((e) => printParseErrorCode(e.error)).join(", ")}`);
  }
  return config;
}

function suffixed(base, previewName) {
  const name = `${base}-${previewName}`;
  if (name.length > MAX_NAME) {
    throw new Error(`"${name}" is longer than ${MAX_NAME} characters; use a shorter Preview name`);
  }
  return name;
}

export function plan(config, previewName) {
  const workflows = config.workflows ?? [];
  if (workflows.length === 0) throw new Error(`${CONFIG} declares no workflows`);
  for (const wf of workflows) {
    if (wf.script_name) {
      throw new Error(`Workflow ${wf.binding} is owned by ${wf.script_name}; this script only ` +
          "handles Workflows defined in this Worker");
    }
  }

  const companionName = suffixed(config.name, previewName);
  const companionWorkflows = workflows.map((wf) => ({
    ...wf,
    name: suffixed(wf.name, previewName),
  }));
  // Cron schedules on a per-Preview Workflow would fire for every open pull request.
  for (const wf of companionWorkflows) delete wf.schedules;

  const localDurableObjects = (config.durable_objects?.bindings ?? [])
      .filter((b) => !b.script_name);
  const vars = { ...config.vars, ...config.previews?.vars, PREVIEW_NAME: previewName };

  const companion = { ...config };
  for (const key of COMPANION_DROP) delete companion[key];
  Object.assign(companion, {
    name: companionName,
    workers_dev: false,
    preview_urls: false,
    vars,
    workflows: companionWorkflows,
  });

  const preview = {
    ...config,
    previews: {
      ...config.previews,
      vars,
      workflows: companionWorkflows.map(({ binding, name, class_name }) => ({
        binding, name, class_name, script_name: companionName,
      })),
      durable_objects: {
        bindings: [
          ...(config.previews?.durable_objects?.bindings ?? [])
              .filter((b) => !localDurableObjects.some((l) => l.name === b.name)),
          ...localDurableObjects.map(({ name, class_name }) => ({
            name, class_name, script_name: companionName,
          })),
        ],
      },
    },
  };

  return { companionName, companionWorkflows, companion, preview };
}

function writeConfigs(p) {
  const header = "// Generated by scripts/preview.mjs. Do not edit or commit.\n";
  writeFileSync(COMPANION_CONFIG, header + JSON.stringify(p.companion, null, 2) + "\n");
  writeFileSync(PREVIEW_CONFIG, header + JSON.stringify(p.preview, null, 2) + "\n");
  console.log(`wrote ${COMPANION_CONFIG} (Worker ${p.companionName}, Workflows ` +
      `${p.companionWorkflows.map((w) => w.name).join(", ")}) and ${PREVIEW_CONFIG}`);
}

function wrangler(args, { capture = false } = {}) {
  console.log(`$ wrangler ${args.join(" ")}`);
  const result = spawnSync("npx", ["wrangler", ...args], {
    encoding: "utf8",
    stdio: capture ? ["ignore", "pipe", "pipe"] : ["ignore", "inherit", "inherit"],
    env: { ...process.env, CI: process.env.CI ?? "true" },
  });
  if (capture) {
    if (result.stderr) process.stderr.write(result.stderr);
  }
  return result;
}

function must(result, what) {
  if (result.status !== 0) {
    if (result.stdout) process.stdout.write(result.stdout);
    throw new Error(`${what} failed with exit code ${result.status}`);
  }
  return result;
}

const isMissing = (r) => /not[ _.]?found|does not exist|10007|10025|10222/i.test(`${r.stdout}${r.stderr}`);

function deploy(p, previewName) {
  // The companion first: the Preview's bindings name its Workflows and Durable Objects.
  must(wrangler(["deploy", "-c", COMPANION_CONFIG]), `deploying ${p.companionName}`);

  const result = must(
      wrangler(["preview", "-c", PREVIEW_CONFIG, "--name", previewName, "--json"], { capture: true }),
      `deploying Preview ${previewName}`);
  const json = JSON.parse(result.stdout.slice(result.stdout.indexOf("{")));
  const url = json.preview?.urls?.[0];
  console.log(`\nPreview ${previewName}: ${url ?? "(no URL)"}`);
  console.log(`Workflows: ${p.companionWorkflows.map((w) => w.name).join(", ")}`);

  if (process.env.GITHUB_OUTPUT) {
    appendFileSync(process.env.GITHUB_OUTPUT, `url=${url ?? ""}\n` +
        `workflows=${p.companionWorkflows.map((w) => w.name).join(",")}\n` +
        `companion=${p.companionName}\n`);
  }
}

function remove(p, previewName) {
  const failures = [];
  const attempt = (args, what) => {
    const r = wrangler(args, { capture: true });
    if (r.status === 0) return;
    if (isMissing(r)) return console.warn(`${what}: already gone`);
    failures.push(`${what} (exit ${r.status})`);
  };
  // Dependents first: the Preview binds to the companion.
  attempt(["preview", "delete", "-c", PREVIEW_CONFIG, "--name", previewName, "-y"],
      `Preview ${previewName}`);
  for (const wf of p.companionWorkflows) {
    attempt(["workflows", "delete", wf.name], `Workflow ${wf.name}`);
  }
  attempt(["delete", "--name", p.companionName, "--force"], `Worker ${p.companionName}`);
  if (failures.length) throw new Error(`cleanup failed: ${failures.join(", ")}`);
}

try {
  const { command, previewName } = parseArgs(process.argv.slice(2));
  const p = plan(readConfig(), previewName);
  writeConfigs(p);
  if (command === "deploy") deploy(p, previewName);
  else if (command === "delete") remove(p, previewName);
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
}
